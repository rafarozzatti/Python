nome = 'Rafael Pires'

# Imprime a letra de indice 0
print(nome[0])
# Imprime as letras do indice 0 até o 5
print(nome[:6])
# Imprime as letras do indice 8 até o final
print(nome[8:])
# Imprime as letras do indice 2 até o 5
print(nome[2:6])
# Imprime as letras do indice 2 até o 5, pulando de 2 em 2
print(nome[2:6:2])
# Imprime uma copia
print(nome[:])
# Imprime uma copia ao contrario
print(nome[::-1])
